from src.reporting import plots

log = logging.getLogger(__name__)


@dataclass
class StrategyReport:
    result: BacktestResult
    metrics: PerformanceMetrics
    benchmark: RandomBenchmarkResult | None = None
    walk_forward: WalkForwardResult | None = None
    sensitivity: pd.DataFrame = field(default_factory=pd.DataFrame)
    label: str = ""

    @property
    def name(self) -> str:
        return self.label or self.result.strategy

    @classmethod
    def build(cls, result: BacktestResult, **kwargs) -> "StrategyReport":
        return cls(result=result, metrics=compute_metrics(result), **kwargs)


# ---------------------------------------------------------------------- #
def _fmt(value, spec: str = ",.2f", dash: str = "-") -> str:
    if value is None:
        return dash
    if isinstance(value, float) and not np.isfinite(value):
        return dash
    try:
        return format(value, spec)
    except (TypeError, ValueError):
        return str(value)


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


