"""Markdown summary report.

The layout is deliberate. Anything that would stop a reasonable person trading the
strategy goes at the very top, in plain language, before any table:

* synthetic data
* costs exceeding gross profit
* the account reaching zero
* position size relative to account size
* failure to beat the random benchmark

Tables come afterwards for the reader who wants the detail. A reader who only sees
the first screen should already know whether the answer is no.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
